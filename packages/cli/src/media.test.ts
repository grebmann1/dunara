let dir: string, engine: Engine, studio: Awaited<ReturnType<typeof startStudio>>, client: Client, server: ReturnType<typeof createMcpServer>;
let projectId: string, otherId: string, bytes: Buffer, headers: Record<string, string>;
const generate = vi.fn();
beforeEach(async () => {
  dir = await mkdtemp(path.join(os.tmpdir(), 'builder-media-api-'));
  bytes = await sharp({ create: { width: 48, height: 48, channels: 3, background: '#448866' } }).png().toBuffer(); generate.mockReset().mockResolvedValue([bytes]);
  engine = new Engine(await Projects.open(path.join(dir, 'apps'), path.join(dir, 'home')), false, false, { run: generate });
  projectId = (await engine.projects.create({ name: 'Media', slug: 'media' })).id;
  otherId = (await engine.projects.create({ name: 'Other', slug: 'other' })).id;
  studio = await startStudio(engine, path.resolve('dist/studio'));
  const auth = await fetch(`${studio.origin}/api/bootstrap`, { method: 'POST', headers: { Origin: studio.origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ ticket: new URL(studio.launchUrl).hash.slice(1) }) });
  headers = { Origin: studio.origin, Authorization: `Bearer ${(await auth.json()).token}`, 'Content-Type': 'application/json' };
  server = createMcpServer(engine); client = new Client({ name: 'media-parity-test', version: '1' });
  const [a, b] = InMemoryTransport.createLinkedPair(); await server.connect(a); await client.connect(b);
});
afterEach(async () => { await client.close(); await server.close(); await studio.close(); await engine.close(); await rm(dir, { recursive: true, force: true }); });
const endpoint = (suffix = '', id = projectId) => `${studio.origin}/api/projects/${id}/media${suffix}`;
const post = (suffix: string, data: unknown, id = projectId) => fetch(endpoint(suffix, id), { method: 'POST', headers, body: JSON.stringify(data) });
const metadata = () => ({ expectedRevision: null, mediaType: 'image/png', label: 'Imported', role: 'illustration', rightsNote: 'Original test image' });
const upload = (extra: Record<string, string> = {}, body = bytes) => fetch(endpoint('/import'), { method: 'POST', headers: { ...headers, 'Content-Type': 'image/png', 'X-Builder-Media': encodeURIComponent(JSON.stringify(metadata())), ...extra }, body: new Uint8Array(body) });
const librarySchema = manifestSchema.extend({ revision: z.string().nullable() }).strip();
it('shares imports, image resources, brief, approvals and transforms with a real MCP protocol client', async () => {
  const imported = await upload(); expect(imported.status).toBe(200);
  let state = librarySchema.parse(await imported.json()); const original = state.assets[0]!;
  const listed = await client.callTool({ name: 'media_list', arguments: { projectId } }); expect(librarySchema.parse(listed.structuredContent)).toEqual(state);
  const read = await client.readResource({ uri: `builder://projects/${projectId}/media/${original.id}` });
  const image = z.object({ blob: z.string() }).parse(read.contents[0]); expect(Buffer.from(image.blob, 'base64')).toEqual((await engine.assets.read(projectId, original.id)).bytes);
  const response = await fetch(endpoint(`/images/${original.id}`), { headers }); expect(response.headers.get('cache-control')).toBe('no-store'); expect(response.headers.get('content-type')).toBe('image/png');
  state = librarySchema.parse((await client.callTool({ name: 'media_approve', arguments: { projectId, input: { assetId: original.id, expectedRevision: state.revision } } })).structuredContent);
  state = librarySchema.parse(await (await post('/brief', { expectedRevision: state.revision, brief: { mood: 'Quiet botanical', referenceIds: [original.id] } })).json());
  expect(librarySchema.parse((await client.callTool({ name: 'media_list', arguments: { projectId } })).structuredContent).brief.mood).toBe('Quiet botanical');
  const result = await client.callTool({ name: 'media_transform', arguments: { projectId, input: { assetId: original.id, expectedRevision: state.revision, width: 32, height: 64, fit: 'contain' } } });
  expect(result.isError).not.toBe(true); state = librarySchema.parse(await (await fetch(endpoint(), { headers })).json());
  expect(state.assets[1]).toMatchObject({ parentId: original.id, width: 32, height: 64, status: 'candidate' });
  expect((await fetch(endpoint(`/images/${original.id}`, otherId), { headers })).status).toBe(400);
  expect((await client.callTool({ name: 'media_read', arguments: { projectId: otherId, assetId: original.id } })).isError).toBe(true);
  expect(generate).not.toHaveBeenCalled();
});
