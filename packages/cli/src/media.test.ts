it('shares icon preparation and config review with MCP while enforcing confirmation and authorization', async () => {
  const imported = librarySchema.parse(await (await upload()).json());
  await post('/approve', { assetId: imported.assets[0]!.id, expectedRevision: imported.revision });
  let library = await engine.assets.list(projectId);
  const result = await client.callTool({ name: 'icon_prepare', arguments: { projectId, input: { assetId: library.assets[0]!.id, expectedRevision: library.revision, kind: 'master', fit: 'contain', background: '#ffffff' } } });
  expect(result.isError).not.toBe(true); library = librarySchema.parse(result.structuredContent);
  const master = library.assets[1]!;
  await post('/approve', { assetId: master.id, expectedRevision: library.revision });
  const selection = { masterId: master.id, background: '#ffffff' };
  const checked = await client.callTool({ name: 'icon_check', arguments: { projectId, input: { assetId: master.id } } });
  expect(checked.structuredContent).toMatchObject({ available: false });
  const proposal = await client.callTool({ name: 'icon_preview', arguments: { projectId, input: selection } });
  expect(proposal.isError).not.toBe(true);
  const diff = z.object({ expectedConfigRevision: z.string(), expectedMediaRevision: z.string(), proposedRevision: z.string(), after: z.string() }).parse(proposal.structuredContent);
  expect(await (await post('/icon-preview', selection)).json()).toMatchObject(diff);
  const confirmation = { ...selection, expectedConfigRevision: diff.expectedConfigRevision, expectedMediaRevision: diff.expectedMediaRevision, proposedRevision: diff.proposedRevision, confirmed: true };
  expect((await post('/icon-apply', { ...confirmation, confirmed: false })).status).toBe(400);
  expect((await fetch(endpoint('/icon-apply'), { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: studio.origin }, body: JSON.stringify(confirmation) })).status).toBe(401);
  expect((await post('/icon-apply', confirmation, otherId)).status).toBe(400);
  expect((await client.callTool({ name: 'icon_apply', arguments: { projectId, input: confirmation } })).isError).not.toBe(true);
  expect((await engine.files.read(projectId, 'app.json')).content).toBe(diff.after);
  expect(generate).not.toHaveBeenCalled();
});
